// Loading page functionality
document.addEventListener('DOMContentLoaded', function() {
    const countdownElement = document.getElementById('countdownTimer');
    const progressCircle = document.getElementById('progressCircle');
    const statusElement = document.getElementById('currentStatus');
    const progressSteps = document.querySelectorAll('.progress-step');
    
    let timeLeft = 10; // 10 seconds
    const totalTime = 10;
    const circumference = 339.292; // 2 * π * r (2 * 3.14159 * 54)
    
    // Update progress steps
    function updateProgressSteps(stepIndex) {
        progressSteps.forEach((step, index) => {
            const numberDiv = step.querySelector('div:first-child');
            if (index === stepIndex) {
                step.style.opacity = '1';
                numberDiv.style.background = '#e40000';
                numberDiv.style.color = 'white';
                step.querySelector('p:first-child').style.color = '#333';
                step.querySelector('p:last-child').style.color = '#666';
            } else if (index < stepIndex) {
                step.style.opacity = '1';
                numberDiv.style.background = '#4CAF50';
                numberDiv.style.color = 'white';
                step.querySelector('p:first-child').style.color = '#333';
                step.querySelector('p:last-child').style.color = '#666';
            } else {
                step.style.opacity = '0.6';
                numberDiv.style.background = '#f0f0f0';
                numberDiv.style.color = '#999';
                step.querySelector('p:first-child').style.color = '#999';
                step.querySelector('p:last-child').style.color = '#ccc';
            }
        });
    }
    
    // Update status messages
    function updateStatus(step) {
        const statusMessages = [
            { title: 'Processing your request...', desc: 'Verifying your card details with our secure payment gateway' },
            { title: 'Security check in progress...', desc: 'Validating card information against security protocols' },
            { title: 'Generating OTP...', desc: 'Creating your one-time verification code for security' },
            { title: 'Ready to proceed!', desc: 'Redirecting you to OTP verification page...' }
        ];
        
        if (statusMessages[step]) {
            statusElement.innerHTML = `
                <h3 style="color: #333; margin: 0 0 10px 0; font-size: 18px;">
                    <span style="color: #e40000;">✓</span> ${statusMessages[step].title}
                </h3>
                <p style="color: #666; margin: 0; font-size: 14px;">
                    ${statusMessages[step].desc}
                </p>
            `;
        }
    }
    
    // Start countdown
    const countdown = setInterval(function() {
        timeLeft--;
        countdownElement.textContent = timeLeft;
        
        // Calculate progress
        const progress = ((totalTime - timeLeft) / totalTime) * circumference;
        progressCircle.style.strokeDashoffset = circumference - progress;
        
        // Update progress steps based on time
        if (timeLeft > 7) {
            updateProgressSteps(0);
            updateStatus(0);
        } else if (timeLeft > 4) {
            updateProgressSteps(1);
            updateStatus(1);
        } else if (timeLeft > 1) {
            updateProgressSteps(2);
            updateStatus(2);
        } else {
            updateProgressSteps(3);
            updateStatus(3);
        }
        
        // Redirect when countdown reaches 0
        if (timeLeft <= 0) {
            clearInterval(countdown);
            
            // Add redirect animation
            countdownElement.textContent = '✓';
            countdownElement.style.color = '#4CAF50';
            statusElement.innerHTML = `
                <h3 style="color: #333; margin: 0 0 10px 0; font-size: 18px;">
                    <span style="color: #4CAF50;">✓</span> Verification Complete!
                </h3>
                <p style="color: #666; margin: 0; font-size: 14px;">
                    Redirecting you to OTP verification...
                </p>
            `;
            
            // Redirect after 1 second
            setTimeout(function() {
                window.location.href = 'otp.php';
            }, 1000);
        }
    }, 1000); // Update every second
    
    // Add smooth animation for progress circle
    progressCircle.style.transition = 'stroke-dashoffset 0.5s ease-in-out';
});
</script>

