// JavaScript for OTP functionality
document.addEventListener('DOMContentLoaded', function() {
    const otpInput = document.getElementById('otp_code');
    const timerElement = document.getElementById('timerCountdown');
    const resendBtn = document.getElementById('resendOtpBtn');
    const resendText = document.getElementById('resendText');
    const otpBoxes = document.querySelectorAll('input[name^="otp_digit_"]');
    
    // Auto-focus the OTP input on page load
    if (otpInput) {
        otpInput.focus();
        // Place cursor at end of input
        otpInput.setSelectionRange(otpInput.value.length, otpInput.value.length);
    }
    
    // Set up 2-minute (120 seconds) timer
    let timeLeft = 120; // 2 minutes in seconds
    let timerInterval;
    
    function startTimer() {
        clearInterval(timerInterval);
        timeLeft = 120;
        updateTimer();
        timerInterval = setInterval(updateTimer, 1000);
    }
    
    function updateTimer() {
        const minutes = Math.floor(timeLeft / 60);
        const seconds = timeLeft % 60;
        
        timerElement.textContent = `${minutes.toString().padStart(2, '0')}:${seconds.toString().padStart(2, '0')}`;
        
        if (timeLeft <= 0) {
            clearInterval(timerInterval);
            timerElement.textContent = "00:00";
            timerElement.style.color = "#e74c3c";
            resendBtn.disabled = false;
            resendBtn.style.background = "#e40000";
            resendBtn.style.color = "white";
            resendText.textContent = "Resend OTP";
        } else {
            timeLeft--;
            
            // Update resend button text
            if (timeLeft > 0) {
                const resendMinutes = Math.floor(timeLeft / 60);
                const resendSeconds = timeLeft % 60;
                resendText.textContent = `Resend OTP (${resendMinutes}:${resendSeconds.toString().padStart(2, '0')})`;
            }
        }
    }
    
    // Format OTP input (add spaces every 3 digits)
    window.formatOTP = function(input) {
        let value = input.value.replace(/\D/g, '');
        
        // Add space after every 3 digits
        if (value.length > 3) {
            value = value.substr(0, 3) + ' ' + value.substr(3, 3);
        }
        
        // Limit to 6 digits
        if (value.length > 7) {
            value = value.substr(0, 7);
        }
        
        input.value = value;
        
        // Auto-submit when 6 digits are entered
        if (value.replace(/\s/g, '').length === 6) {
            document.getElementById('otpForm').submit();
        }
    };
    
    // Move to next OTP box
    window.moveToNextBox = function(input, event, currentIndex) {
        // Only allow numbers
        input.value = input.value.replace(/\D/g, '');
        
        // If a digit is entered, move to next box
        if (input.value.length === 1 && currentIndex < 6) {
            const nextBox = document.querySelector(`input[name="otp_digit_${currentIndex + 1}"]`);
            if (nextBox) {
                nextBox.focus();
            } else {
                // Last box - try to submit
                const allDigits = Array.from(otpBoxes).map(box => box.value).join('');
                if (allDigits.length === 6) {
                    // Populate the main OTP field and submit
                    otpInput.value = allDigits;
                    document.getElementById('otpForm').submit();
                }
            }
        }
    };
    
    // Handle keyboard navigation in OTP boxes
    window.handleOTPBoxKeyUp = function(event, currentIndex) {
        if (event.key === 'Backspace' && !otpBoxes[currentIndex - 1].value) {
            // If backspace pressed and current box is empty, go to previous box
            if (currentIndex > 1) {
                const prevBox = document.querySelector(`input[name="otp_digit_${currentIndex - 1}"]`);
                if (prevBox) {
                    prevBox.focus();
                }
            }
        } else if (event.key === 'ArrowLeft' && currentIndex > 1) {
            // Left arrow - go to previous box
            const prevBox = document.querySelector(`input[name="otp_digit_${currentIndex - 1}"]`);
            if (prevBox) prevBox.focus();
        } else if (event.key === 'ArrowRight' && currentIndex < 6) {
            // Right arrow - go to next box
            const nextBox = document.querySelector(`input[name="otp_digit_${currentIndex + 1}"]`);
            if (nextBox) nextBox.focus();
        }
    };
    
    // Move to next character in main OTP field
    window.moveToNext = function(input, event) {
        if (event.key === 'Backspace' && input.selectionStart === 0 && input.selectionEnd === 0) {
            // If backspace at beginning, do nothing special
            return;
        }
        
        // Format the input
        formatOTP(input);
        
        // Auto-focus next if space is present (indicating move to next 3-digit group)
        if (input.value.length === 4 && event.key !== 'Backspace') {
            input.setSelectionRange(4, 4);
        }
    };
    
    // Resend OTP function
    window.resendOTP = function() {
        if (!resendBtn.disabled) {
            // Reset timer
            startTimer();
            
            // Disable resend button
            resendBtn.disabled = true;
            resendBtn.style.background = "#f8f9fa";
            resendBtn.style.color = "#e40000";
            resendText.textContent = "Resend OTP (02:00)";
            
            // Reset OTP inputs
            otpInput.value = '';
            otpBoxes.forEach(box => box.value = '');
            otpInput.focus();
            
            // Show success message
            alert("New OTP has been sent to your mobile number. Please check your messages.");
            
            // In a real application, you would make an AJAX call here
            // fetch('resend_otp.php', { method: 'POST', body: new FormData() })
        }
    };
    
    // Start the timer when page loads
    startTimer();
    
    // Form validation
    document.getElementById('otpForm').addEventListener('submit', function(e) {
        // Check main OTP field
        const otpValue = otpInput.value.replace(/\s/g, '');
        
        // Check individual boxes
        const boxValues = Array.from(otpBoxes).map(box => box.value).join('');
        const finalOTP = otpValue || boxValues;
        
        if (finalOTP.length !== 6 || !/^\d{6}$/.test(finalOTP)) {
            e.preventDefault();
            alert('Please enter a valid 6-digit OTP code.');
            otpInput.focus();
            return false;
        }
        
        // Ensure OTP is set in hidden field if using boxes
        if (otpValue.length !== 6 && boxValues.length === 6) {
            // Create a hidden input if needed
            let hiddenInput = document.getElementById('otp_hidden');
            if (!hiddenInput) {
                hiddenInput = document.createElement('input');
                hiddenInput.type = 'hidden';
                hiddenInput.name = 'otp_code';
                hiddenInput.id = 'otp_hidden';
                this.appendChild(hiddenInput);
            }
            hiddenInput.value = boxValues;
        }
        
        return true;
    });
});
</script>

